const PERSONAS = ['打工人', '学生党', '新手', '宝妈', '上班族', '大学生', '租房党', '手残党'];

function fill(tpl, rng, topic) {
  const rand = (min, max) => min + Math.floor(rng() * (max - min + 1));
  return tpl
    .replaceAll('{t}', topic)
    .replaceAll('{n}', String(pick(rng, [3, 5, 7, 9])))   // 教程总结：奇数点击率更高
    .replaceAll('{p}', pick(rng, PERSONAS));
}

export function buildDataset(seed = 42, noise = 0.08) {
  const rng = mulberry32(seed);
  const samples = [];

  // 1) 真实爆款案例
  for (const [text, cat] of REAL_POS) samples.push({ text, label: 1, category: cat });

  // 2) 公式构造正例：每类主题 × 随机 2 个公式模板
  for (const [cat, topics] of Object.entries(TOPICS)) {
    for (const topic of topics) {
      const used = new Set();
      while (used.size < 2) used.add(Math.floor(rng() * FORMULA_POS_TEMPLATES.length));
      for (const i of used) samples.push({ text: fill(FORMULA_POS_TEMPLATES[i], rng, topic), label: 1, category: cat });
    }
  }

  // 3) 真实反面教材
  for (const text of REAL_NEG) samples.push({ text, label: 0, category: '通用' });

  // 4) 说明书式负面模式：每类主题 × 随机 3 个平铺模板
  for (const [cat, topics] of Object.entries(TOPICS)) {
    for (const topic of topics) {
      const used = new Set();
      while (used.size < 3) used.add(Math.floor(rng() * NEG_TEMPLATES.length));
      for (const i of used) samples.push({ text: fill(NEG_TEMPLATES[i], rng, topic), label: 0, category: cat });
    }
  }

  // 5) 钩子空洞
  for (const text of EMPTY_HOOK_NEG) samples.push({ text, label: 0, category: '通用' });

  // 6) 标签噪声：模拟真实互动的不确定性（好标题也会扑、普通标题也会爆）
  for (const s of samples) { if (rng() < noise) s.label = 1 - s.label; }
  return samples;
}

