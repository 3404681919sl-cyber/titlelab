const PERSONAS = ['打工人', '学生党', '新手', '宝妈', '上班族', '大学生', '独居', '租房党', '懒人', '手残党'];

function fill(tpl, rng, topic) {
  const rand = (min, max) => min + Math.floor(rng() * (max - min + 1));
  return tpl
    .replaceAll('{t}', topic)
    .replaceAll('{n}', rand(3, 30))
    .replaceAll('{n2}', rand(3, 15))
    .replaceAll('{k}', rand(3, 8))
    .replaceAll('{p}', pick(rng, PERSONAS));
}

export function buildDataset(seed = 42, noise = 0.10) {
  const rng = mulberry32(seed);
  const samples = [];
  for (const [cat, topics] of Object.entries(TOPICS)) {
    for (const topic of topics) {
      const posPicks = new Set();
      while (posPicks.size < 2) posPicks.add(Math.floor(rng() * POS_TEMPLATES.length));
      for (const i of posPicks) samples.push({ text: fill(POS_TEMPLATES[i], rng, topic), label: 1, category: cat });
      const negPicks = new Set();
      while (negPicks.size < 3) negPicks.add(Math.floor(rng() * NEG_TEMPLATES.length));
      for (const i of negPicks) samples.push({ text: fill(NEG_TEMPLATES[i], rng, topic), label: 0, category: cat });
    }
  }
  for (const t of HARD_NEG) samples.push({ text: t, label: 0, category: '通用' });
  for (const t of HARD_POS) samples.push({ text: t, label: 1, category: '通用' });

  // 注入标签噪声，模拟真实互动数据的不确定性（好标题也会扑、普通标题也会爆）
  for (const s of samples) { if (rng() < noise) s.label = 1 - s.label; }
  return samples;
}

